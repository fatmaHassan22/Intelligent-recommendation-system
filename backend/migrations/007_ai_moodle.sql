CREATE TABLE ai_conversations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,title VARCHAR(120) NOT NULL,
 created_at DATETIME(3) NOT NULL,updated_at DATETIME(3) NOT NULL,UNIQUE(id,user_id),INDEX(user_id,updated_at),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
CREATE TABLE ai_chat_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,conversation_id BIGINT UNSIGNED NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,prompt_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 status ENUM('RUNNING','COMPLETED','FAILED') NOT NULL,attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,error_code VARCHAR(64) CHARACTER SET ascii NULL,
 lease_until DATETIME(3) NOT NULL,created_at DATETIME(3) NOT NULL,updated_at DATETIME(3) NOT NULL,
 UNIQUE(user_id,request_id),INDEX(user_id,status,lease_until),
 FOREIGN KEY(conversation_id,user_id) REFERENCES ai_conversations(id,user_id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE ai_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,conversation_id BIGINT UNSIGNED NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,role ENUM('USER','ASSISTANT') NOT NULL,
 content TEXT NOT NULL,origin ENUM('STUDENT','GEMINI','DETERMINISTIC') NOT NULL,context_scope ENUM('NONE','ACADEMIC','MOODLE','BOTH') NOT NULL DEFAULT 'NONE',
 metadata JSON NOT NULL,created_at DATETIME(3) NOT NULL,UNIQUE(conversation_id,request_id,role),INDEX(conversation_id,id),
 FOREIGN KEY(conversation_id,user_id) REFERENCES ai_conversations(id,user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
CREATE TABLE ai_usage_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,request_row_id BIGINT UNSIGNED NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,attempt TINYINT UNSIGNED NOT NULL,
 model VARCHAR(100) CHARACTER SET ascii NOT NULL,status ENUM('RESERVED','COMPLETED','FAILED') NOT NULL,
 input_characters INT UNSIGNED NOT NULL,output_characters INT UNSIGNED NOT NULL DEFAULT 0,input_tokens INT UNSIGNED NULL,output_tokens INT UNSIGNED NULL,
 error_code VARCHAR(64) CHARACTER SET ascii NULL,created_at DATETIME(3) NOT NULL,UNIQUE(user_id,request_id,attempt),INDEX(user_id,created_at),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,FOREIGN KEY(request_row_id) REFERENCES ai_chat_requests(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE moodle_connections (
 user_id BIGINT UNSIGNED PRIMARY KEY,token_cipher TEXT NULL,moodle_user_id BIGINT UNSIGNED NULL,
 state ENUM('NOT_CONFIGURED','CONFIGURED','CONNECTED','AUTHENTICATION_FAILED','PERMISSION_DENIED','SYNC_ERROR') NOT NULL DEFAULT 'NOT_CONFIGURED',
 enabled BOOLEAN NOT NULL DEFAULT FALSE,notifications_enabled BOOLEAN NOT NULL DEFAULT TRUE,revision INT UNSIGNED NOT NULL DEFAULT 1,
 capabilities JSON NOT NULL,last_attempt_at DATETIME(3) NULL,last_success_at DATETIME(3) NULL,next_sync_at DATETIME(3) NULL,
 error_code VARCHAR(64) CHARACTER SET ascii NULL,updated_at DATETIME(3) NOT NULL,
 INDEX(enabled,next_sync_at),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE moodle_courses (
 user_id BIGINT UNSIGNED NOT NULL,external_id BIGINT UNSIGNED NOT NULL,name VARCHAR(255) NOT NULL,shortname VARCHAR(255) NOT NULL,
 source_url VARCHAR(2048) NULL,is_active BOOLEAN NOT NULL DEFAULT TRUE,last_seen_at DATETIME(3) NOT NULL,
 PRIMARY KEY(user_id,external_id),FOREIGN KEY(user_id) REFERENCES moodle_connections(user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
CREATE TABLE moodle_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,external_course_id BIGINT UNSIGNED NOT NULL,
 external_id VARCHAR(150) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,kind ENUM('ASSIGNMENT','QUIZ','ANNOUNCEMENT','CALENDAR','MATERIAL') NOT NULL,
 title VARCHAR(255) NOT NULL,description TEXT NOT NULL,due_at DATETIME(3) NULL,published_at DATETIME(3) NULL,source_url VARCHAR(2048) NULL,
 metadata JSON NOT NULL,content_hash CHAR(64) CHARACTER SET ascii NOT NULL,is_active BOOLEAN NOT NULL DEFAULT TRUE,last_seen_at DATETIME(3) NOT NULL,
 UNIQUE(user_id,kind,external_id),INDEX(user_id,is_active,due_at),
 FOREIGN KEY(user_id,external_course_id) REFERENCES moodle_courses(user_id,external_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
CREATE TABLE moodle_sync_runs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,trigger_type ENUM('MANUAL','SCHEDULED') NOT NULL,
 status ENUM('RUNNING','COMPLETED','FAILED') NOT NULL,started_at DATETIME(3) NOT NULL,finished_at DATETIME(3) NULL,
 error_code VARCHAR(64) CHARACTER SET ascii NULL,summary JSON NOT NULL,INDEX(user_id,started_at),
 FOREIGN KEY(user_id) REFERENCES moodle_connections(user_id) ON DELETE CASCADE
) ENGINE=InnoDB;
